  var KEY = 'clash-yml-lang';
  var current = 'zh-CN';
  try {
    var saved = localStorage.getItem(KEY);
    if (saved && (saved === 'zh-CN' || DICT[saved])) current = saved;
  } catch (e) { /* localStorage 不可用时用默认 */ }

  function t(zh, a0, a1, a2, a3) {
    var s = zh;
    if (current !== 'zh-CN' && DICT[current] && DICT[current][zh]) s = DICT[current][zh];
    if (a0 !== undefined) s = s.split('{0}').join(String(a0));
    if (a1 !== undefined) s = s.split('{1}').join(String(a1));
    if (a2 !== undefined) s = s.split('{2}').join(String(a2));
    if (a3 !== undefined) s = s.split('{3}').join(String(a3));
    return s;
  }

  // 遍历文本节点与 placeholder，把与词典 key 完全一致的文案换成当前语言。
  // 每个节点的中文原文记在 WeakMap 里，切换语言时永远从原文翻译，任意语言之间可来回切。
  // 跳过 script/style/textarea 和带 data-no-i18n 的子树，避免动到用户输入与 YAML 内容。
  var origText = new WeakMap();
  var origPh = new WeakMap();
  function apply(root) {
    var dict = current === 'zh-CN' ? null : DICT[current];
    var walker = document.createTreeWalker(root || document.body, NodeFilter.SHOW_TEXT, {
      acceptNode: function (node) {
        var p = node.parentElement;
        if (!p) return NodeFilter.FILTER_REJECT;
        var tag = p.tagName;
        if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'TEXTAREA') return NodeFilter.FILTER_REJECT;
        if (p.closest && p.closest('[data-no-i18n]')) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    var nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(function (node) {
      if (!origText.has(node)) origText.set(node, node.nodeValue);
      var raw = origText.get(node);
      var trimmed = raw.trim();
      if (trimmed && dict && dict[trimmed]) node.nodeValue = raw.replace(trimmed, dict[trimmed]);
      else node.nodeValue = raw;
    });
    (root || document.body).querySelectorAll('[placeholder]').forEach(function (el) {
      if (!origPh.has(el)) origPh.set(el, el.getAttribute('placeholder'));
      var ph = origPh.get(el);
      el.setAttribute('placeholder', (dict && ph && dict[ph]) ? dict[ph] : ph);
    });
  }

